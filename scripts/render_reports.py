"""Formatting only (added after pre-registration; see docs/DEVIATIONS.md D3).

Computes nothing new. It copies generated values into report files:
- docs/PREDICTION_OUTCOMES.md: each prediction's pre-registered text (from
  docs/PREREGISTRATION.md section 7) next to its verdict and evidence, copied
  verbatim from results/summary/predictions.csv. HOLDS is shown as HELD and
  FAILS as FAILED. A prediction with no row is NOT EVALUABLE.
- results/summary/per_pair_policy_x_verifier.csv: the rows of
  results/summary/per_pair.csv whose roles column is "policy-side x verifier-side".

Usage: python3 scripts/render_reports.py
"""

import csv
import re

with open("docs/PREREGISTRATION.md", encoding="utf-8") as f:
    prereg = f.read()
section = prereg[prereg.index("## 7. Predictions"):prereg.index("## 8. Analysis plan")]
statements = dict(re.findall(r"^- \*\*(P\d+)(?: \(primary\))?\.\*\* (.+)$", section, flags=re.M))

with open("results/summary/predictions.csv", newline="", encoding="utf-8") as f:
    rows = {r["prediction"]: r for r in csv.DictReader(f)}

verdict = {"HOLDS": "HELD", "FAILS": "FAILED"}
ids = sorted(statements, key=lambda p: int(p[1:]))
lines = [
    "# Prediction outcomes (corpus v1)",
    "",
    "Generated by `scripts/render_reports.py` from `results/summary/predictions.csv`, which",
    "`scripts/check_predictions.py` writes from the committed raw results. The prediction text is",
    "copied verbatim from `docs/PREREGISTRATION.md` section 7. The evidence column is the checking",
    "function's own output.",
    "",
]
counts = {"HELD": 0, "FAILED": 0, "NOT EVALUABLE": 0}
table = ["| # | Pre-registered prediction | Outcome | Deciding script output |", "|---|---|---|---|"]
for p in ids:
    r = rows.get(p)
    v = verdict[r["result"]] if r else "NOT EVALUABLE"
    counts[v] += 1
    ev = r["evidence"] if r else "no output from scripts/check_predictions.py"
    table.append(f"| {p} | {statements[p].replace('|', '/')} | **{v}** | `{ev.replace('|', '/')}` |")
lines.append(f"Held: {counts['HELD']}. Failed: {counts['FAILED']}. Not evaluable: {counts['NOT EVALUABLE']}. Total: {len(ids)}.")
lines.append("")
lines += table
lines.append("")
with open("docs/PREDICTION_OUTCOMES.md", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

with open("results/summary/per_pair.csv", newline="", encoding="utf-8") as f:
    rd = csv.reader(f)
    header = next(rd)
    sub = [r for r in rd if r[header.index("roles")] == "policy-side x verifier-side"]
with open("results/summary/per_pair_policy_x_verifier.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(header)
    w.writerows(sub)
print(f"wrote docs/PREDICTION_OUTCOMES.md ({len(ids)} predictions) and {len(sub)} policy x verifier rows")
